export const normalizeWord = value => String(value).toLocaleLowerCase('ru').replaceAll('ё','е').replace(/[^а-я]/g,'');
function prepare(state, random) {
  const word=state.items[state.index].word;
  state.letters=shuffle([...word],random);
  if (state.letters.join('')===word) state.letters.push(state.letters.shift());
  state.answer=''; state.message=''; state.status='playing';
}
export function createWords(random=Math.random) {
  const state={items:shuffle(WORDS,random).slice(0,10),index:0,solved:0,hints:0,answer:'',letters:[],message:'',status:'playing'};
  prepare(state,random); return state;
}
export function submitWord(state) {
  if (state.status!=='playing') return false;
  if (normalizeWord(state.answer)!==normalizeWord(state.items[state.index].word)) { state.message='Не подходит. Попробуй ещё.'; return false; }
  state.solved++; state.message='Верно'; state.status=state.solved===state.items.length?'won':'between'; return true;
}
export function nextWord(state,random=Math.random) { if(state.status!=='between')return;state.index++;prepare(state,random); }
export function hintWord(state) {
  if(state.status!=='playing')return;
  const word=state.items[state.index].word; let prefix=0;
  while(prefix<word.length&&normalizeWord(state.answer[prefix]||'')===normalizeWord(word[prefix]))prefix++;
  state.answer=word.slice(0,Math.min(word.length,prefix+1)); state.hints++;state.message='';
}
export function availableLetters(state) {
  const used=new Map(); for(const char of normalizeWord(state.answer))used.set(char,(used.get(char)||0)+1);
  return state.letters.map(char=>{const key=normalizeWord(char);const count=used.get(key)||0;if(count){used.set(key,count-1);return false;}return true;});
}
